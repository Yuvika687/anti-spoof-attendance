"""
evaluate_gray_zone.py
------------------------
Three-way decision analysis: LIVE / SPOOF / UNCERTAIN.

The UNCERTAIN band [0.5 - half_width, 0.5 + half_width] on P(spoof) is
chosen using ONLY the validation set (outputs/predictions/predictions_val.csv,
generated by evaluate.py), searching for the half_width that puts closest
to a target fraction (default 5%) of validation samples inside the band.
The test set is never used for band selection -- it's a fixed, carried-over
band evaluated strictly after the fact, so this is a real held-out
evaluation of the policy, not a test-set-tuned one.

This is analysis only: it does not change the model, the backend, or the
live threshold. It reports what a 3-way policy WOULD do if applied.

Usage:
    python evaluate_gray_zone.py --target_uncertain_frac 0.05
"""

import argparse
import csv
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

import config


def load_probs(csv_path: str):
    """Returns (true_labels, prob_spoof) numpy arrays from an evaluate.py
    predictions CSV."""
    true_labels, probs, filepaths = [], [], []
    with open(csv_path) as f:
        for row in csv.DictReader(f):
            true_labels.append(int(row["true_label"]))
            probs.append(float(row["prob_spoof"]))
            filepaths.append(row["filepath"])
    return np.array(true_labels), np.array(probs), filepaths


def find_band_half_width(val_probs: np.ndarray, target_frac: float, threshold: float = 0.5,
                          search_max: float = 0.49, search_steps: int = 2000) -> float:
    """Scans half_width from 0 up to search_max and returns the value whose
    resulting UNCERTAIN fraction on the VALIDATION set is closest to
    target_frac. A fine linear scan (not a closed-form solution) because
    the distribution of real probabilities is not smooth/known in advance."""
    best_hw, best_diff = 0.0, abs(0.0 - target_frac)
    for hw in np.linspace(0.0, search_max, search_steps):
        low, high = threshold - hw, threshold + hw
        frac = float(np.mean((val_probs >= low) & (val_probs <= high)))
        diff = abs(frac - target_frac)
        if diff < best_diff:
            best_diff, best_hw = diff, hw
    return best_hw


def three_way_decision(probs: np.ndarray, low: float, high: float, threshold: float = 0.5):
    """Returns an array of 0=LIVE, 1=SPOOF, -1=UNCERTAIN per sample."""
    decisions = np.where(probs >= threshold, config.LABEL_SPOOF, config.LABEL_LIVE)
    uncertain_mask = (probs >= low) & (probs <= high)
    decisions = decisions.astype(int)
    decisions[uncertain_mask] = -1
    return decisions


def metrics_on_decided(true_labels: np.ndarray, decisions: np.ndarray):
    """Computes accuracy/APCER/BPCER/HTER using only non-UNCERTAIN samples."""
    decided_mask = decisions != -1
    n_total = len(true_labels)
    n_decided = int(decided_mask.sum())
    coverage = n_decided / n_total if n_total else float("nan")

    y_true = true_labels[decided_mask]
    y_pred = decisions[decided_mask]

    spoof_mask = y_true == config.LABEL_SPOOF
    live_mask = y_true == config.LABEL_LIVE

    apcer = float(np.mean(y_pred[spoof_mask] == config.LABEL_LIVE)) if spoof_mask.sum() else float("nan")
    bpcer = float(np.mean(y_pred[live_mask] == config.LABEL_SPOOF)) if live_mask.sum() else float("nan")
    hter = (apcer + bpcer) / 2
    accuracy = float(np.mean(y_true == y_pred)) if n_decided else float("nan")

    return {
        "n_total": n_total,
        "n_decided": n_decided,
        "n_uncertain": n_total - n_decided,
        "coverage": coverage,
        "accuracy": accuracy,
        "apcer": apcer,
        "bpcer": bpcer,
        "hter": hter,
    }


def main():
    parser = argparse.ArgumentParser(description="Three-way LIVE/SPOOF/UNCERTAIN gray-zone analysis")
    parser.add_argument("--val_csv", default=os.path.join(config.PREDICTIONS_DIR, "predictions_val.csv"))
    parser.add_argument("--test_csv", default=os.path.join(config.PREDICTIONS_DIR, "predictions_test.csv"))
    parser.add_argument("--target_uncertain_frac", type=float, default=0.05)
    parser.add_argument("--threshold", type=float, default=config.DECISION_THRESHOLD)
    parser.add_argument("--out_json", default=os.path.join(config.PROJECT_ROOT, "results", "gray_zone.json"))
    parser.add_argument("--out_plot", default=os.path.join(config.PROJECT_ROOT, "results", "plots", "gray_zone_coverage_vs_error.png"))
    parser.add_argument("--annotation_lookup_root", default=None,
                         help="Use when --test_csv was generated from real (non-symlink) files that "
                              "still share filenames 1:1 with the original symlinked subset -- e.g. "
                              "data/celeba_spoof_cropped, built by build_face_cropped_dataset.py. "
                              "PC-replay annotation lookup then uses this root's matching symlink "
                              "instead. Defaults to None (original behavior, unchanged).")
    args = parser.parse_args()

    for path in (args.val_csv, args.test_csv):
        if not os.path.isfile(path):
            raise SystemExit(f"{path} not found -- run evaluate.py on that split first.")

    print(f"Loading validation predictions from {args.val_csv} ...")
    val_true, val_probs, _ = load_probs(args.val_csv)
    print(f"  {len(val_probs)} validation samples.")

    print(f"Loading test predictions from {args.test_csv} ...")
    test_true, test_probs, test_files = load_probs(args.test_csv)
    print(f"  {len(test_probs)} test samples.")

    half_width = find_band_half_width(val_probs, args.target_uncertain_frac, args.threshold)
    low, high = args.threshold - half_width, args.threshold + half_width
    val_frac_achieved = float(np.mean((val_probs >= low) & (val_probs <= high)))
    print(f"\nBand selected on VALIDATION set (target {args.target_uncertain_frac*100:.1f}% uncertain): "
          f"[{low:.4f}, {high:.4f}]  (half_width={half_width:.4f})")
    print(f"Actual validation UNCERTAIN fraction achieved: {val_frac_achieved*100:.2f}%")

    # Apply the VAL-selected, now-fixed band to the TEST set.
    test_decisions = three_way_decision(test_probs, low, high, args.threshold)
    test_metrics = metrics_on_decided(test_true, test_decisions)

    # Baseline: plain-threshold, no UNCERTAIN band (real numbers from evaluate.py's own run).
    baseline_decisions = np.where(test_probs >= args.threshold, config.LABEL_SPOOF, config.LABEL_LIVE)
    baseline_metrics = metrics_on_decided(test_true, baseline_decisions)  # decisions never -1, so coverage=100%

    print("\n=== TEST SET: plain threshold (baseline) vs gray-zone (decided samples only) ===")
    print(f"{'Metric':<12}{'Baseline':<14}{'Gray-zone (decided)':<22}")
    for key in ("accuracy", "apcer", "bpcer", "hter"):
        print(f"{key:<12}{baseline_metrics[key]*100:<14.2f}{test_metrics[key]*100:<22.2f}")
    print(f"\nCoverage (% of test decided): {test_metrics['coverage']*100:.2f}%  "
          f"({test_metrics['n_decided']}/{test_metrics['n_total']})")
    print(f"UNCERTAIN on test set: {test_metrics['n_uncertain']} samples")

    # How many of the real 22 false accepts / 11 false rejects land in UNCERTAIN?
    false_accept_mask = (test_true == config.LABEL_SPOOF) & (baseline_decisions == config.LABEL_LIVE)
    false_reject_mask = (test_true == config.LABEL_LIVE) & (baseline_decisions == config.LABEL_SPOOF)
    uncertain_mask = test_decisions == -1

    n_false_accepts = int(false_accept_mask.sum())
    n_false_rejects = int(false_reject_mask.sum())
    fa_rescued = int((false_accept_mask & uncertain_mask).sum())
    fr_rescued = int((false_reject_mask & uncertain_mask).sum())

    print(f"\nOf {n_false_accepts} real false accepts: {fa_rescued} now fall in UNCERTAIN "
          f"(deferred instead of wrongly accepted)")
    print(f"Of {n_false_rejects} real false rejects: {fr_rescued} now fall in UNCERTAIN "
          f"(deferred instead of wrongly rejected)")

    # PC-replay false accepts specifically -- cross-reference official spoof type.
    from evaluate_breakdown import SPOOF_TYPE_NAMES, load_official_labels
    raw_root = os.path.join(config.PROJECT_ROOT, "raw_downloads", "CelebA_Spoof", "CelebA_Spoof")
    pc_fa_rescued = None
    if os.path.isdir(raw_root):
        official_labels = load_official_labels(raw_root)
        raw_root_abs = os.path.abspath(raw_root)
        pc_total = 0
        pc_rescued = 0
        for i, fp in enumerate(test_files):
            if not false_accept_mask[i]:
                continue
            # When --test_csv was generated from a dataset of REAL (non-
            # symlink) files that still share filenames 1:1 with the
            # original symlinked subset (e.g. data/celeba_spoof_cropped,
            # built by build_face_cropped_dataset.py), resolve the
            # official-label lookup via the matching file in
            # --annotation_lookup_root's symlinked subset instead --
            # realpath-ing fp directly would just return fp itself and
            # silently match nothing.
            if args.annotation_lookup_root:
                class_name = os.path.basename(os.path.dirname(fp))
                lookup_path = os.path.join(args.annotation_lookup_root, class_name, os.path.basename(fp))
            else:
                lookup_path = fp
            real = os.path.realpath(lookup_path)
            rel = os.path.normpath(os.path.relpath(real, raw_root_abs))
            attrs = official_labels.get(rel)
            if attrs is None:
                continue
            spoof_type_name = SPOOF_TYPE_NAMES.get(attrs[40])
            if spoof_type_name == "PC":
                pc_total += 1
                if uncertain_mask[i]:
                    pc_rescued += 1
        pc_fa_rescued = {"pc_false_accepts_total": pc_total, "pc_false_accepts_in_uncertain": pc_rescued}
        print(f"\nOf {pc_total} PC-replay false accepts specifically: {pc_rescued} now fall in UNCERTAIN")
    else:
        print(f"\n(Skipping PC-replay breakdown -- raw CelebA-Spoof download not found at {raw_root})")

    # ------------------------------------------------------------------
    # Coverage-vs-error curve: sweep half_width, apply to TEST set (this
    # sweep itself is just a descriptive curve, not re-selecting the band
    # used above, which stays fixed from the validation-only search).
    # ------------------------------------------------------------------
    # Sweep all the way to the same search_max used for band selection (plus
    # a hair past it) so the chosen band always lands ON the curve, not
    # beyond its last point -- a real bug caught by looking at the first
    # render of this plot (the sweep stopped at 0.45, the chosen band was
    # 0.49, leaving the red point visually disconnected from the curve).
    sweep_half_widths = np.linspace(0.0, 0.499, 100)
    curve = []
    for hw in sweep_half_widths:
        lo, hi = args.threshold - hw, args.threshold + hw
        dec = three_way_decision(test_probs, lo, hi, args.threshold)
        m = metrics_on_decided(test_true, dec)
        curve.append({"half_width": float(hw), "coverage": m["coverage"], "hter": m["hter"],
                       "apcer": m["apcer"], "bpcer": m["bpcer"]})

    os.makedirs(os.path.dirname(args.out_plot), exist_ok=True)
    fig, ax1 = plt.subplots(figsize=(7, 5))
    coverages = [c["coverage"] * 100 for c in curve]
    hters = [c["hter"] * 100 for c in curve]
    ax1.plot(coverages, hters, color="#2874a6", marker="o", markersize=3)
    ax1.scatter([test_metrics["coverage"] * 100], [test_metrics["hter"] * 100],
                color="#c0392b", zorder=5, s=60, label=f"Chosen band (half_width={half_width:.3f})")
    ax1.set_xlabel("Coverage (%) -- fraction of test samples decided")
    ax1.set_ylabel("HTER (%) on decided samples")
    ax1.set_title("Coverage vs. HTER as the UNCERTAIN band widens")
    ax1.grid(alpha=0.3)
    ax1.legend()
    fig.tight_layout()
    fig.savefig(args.out_plot, dpi=150)
    plt.close(fig)
    print(f"\nSaved coverage-vs-error curve to: {args.out_plot}")

    # ------------------------------------------------------------------
    # Save JSON
    # ------------------------------------------------------------------
    output = {
        "target_uncertain_fraction": args.target_uncertain_frac,
        "band_selected_on": "validation set only (predictions_val.csv) -- test set never used for band selection",
        "threshold": args.threshold,
        "band_half_width": float(half_width),
        "band_low": float(low),
        "band_high": float(high),
        "validation_uncertain_fraction_achieved": val_frac_achieved,
        "test_baseline_plain_threshold": baseline_metrics,
        "test_gray_zone_decided_only": test_metrics,
        "false_accepts_rescued_to_uncertain": fa_rescued,
        "false_accepts_total": n_false_accepts,
        "false_rejects_rescued_to_uncertain": fr_rescued,
        "false_rejects_total": n_false_rejects,
        "pc_replay_false_accepts": pc_fa_rescued,
        "coverage_vs_error_curve": curve,
    }
    os.makedirs(os.path.dirname(args.out_json), exist_ok=True)
    with open(args.out_json, "w") as f:
        json.dump(output, f, indent=2)
    print(f"Saved gray-zone results to: {args.out_json}")


if __name__ == "__main__":
    main()
